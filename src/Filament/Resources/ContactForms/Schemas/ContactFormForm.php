<?php

declare(strict_types=1);

namespace Madbox99\FilamentContactForm\Filament\Resources\ContactForms\Schemas;

use Filament\Forms\Components\CodeEditor;
use Filament\Forms\Components\CodeEditor\Enums\Language;
use Filament\Forms\Components\ColorPicker;
use Filament\Forms\Components\Select;
use Filament\Forms\Components\TagsInput;
use Filament\Forms\Components\Textarea;
use Filament\Forms\Components\TextInput;
use Filament\Forms\Components\Toggle;
use Filament\Schemas\Components\Group;
use Filament\Schemas\Components\Section;
use Filament\Schemas\Components\Utilities\Set;
use Filament\Schemas\Schema;
use Illuminate\Support\Str;
use Madbox99\FilamentContactForm\Enums\FieldVisibility;
use Madbox99\FilamentContactForm\Support\CssSanitizer;
use Madbox99\FilamentContactForm\ValueObjects\DesignTokens;

final class ContactFormForm
{
    public static function configure(Schema $schema): Schema
    {
        return $schema
            ->columns(3)
            ->components([
                Group::make()
                    ->columnSpan(2)
                    ->schema([
                        self::detailsSection(),
                        self::fieldsSection(),
                        self::submissionSection(),
                        self::designSection(),
                        self::customCssSection(),
                    ]),
                self::crmSection(),
            ]);
    }

    /**
     * The slug to fill in when the name changes, or `null` when editing an
     * existing form whose URL is already embedded somewhere.
     */
    public static function autoGeneratedSlug(?string $name, string $operation): ?string
    {
        if ($operation !== 'create') {
            return null;
        }

        return Str::slug((string) $name);
    }

    private static function detailsSection(): Section
    {
        return Section::make(__('filament-contact-form::contact.sections.form_details'))
            ->schema([
                TextInput::make('name')
                    ->label(__('filament-contact-form::contact.fields.name'))
                    ->helperText(__('filament-contact-form::contact.helpers.name'))
                    ->required()
                    ->maxLength(255)
                    ->live(onBlur: true)
                    ->afterStateUpdated(static function (?string $state, Set $set, string $operation): void {
                        $slug = self::autoGeneratedSlug($state, $operation);

                        if ($slug !== null) {
                            $set('slug', $slug);
                        }
                    }),
                TextInput::make('slug')
                    ->label(__('filament-contact-form::contact.fields.slug'))
                    ->required()
                    ->unique(ignoreRecord: true)
                    ->regex('/^[a-z0-9-]+$/')
                    ->maxLength(128),
                TextInput::make('title')
                    ->label(__('filament-contact-form::contact.fields.title'))
                    ->helperText(__('filament-contact-form::contact.helpers.title'))
                    ->maxLength(255),
                TextInput::make('submit_label')
                    ->label(__('filament-contact-form::contact.fields.submit_label'))
                    ->placeholder(__('filament-contact-form::contact.submit'))
                    ->maxLength(255),
                Textarea::make('description')
                    ->label(__('filament-contact-form::contact.fields.description'))
                    ->maxLength(65535)
                    ->columnSpanFull(),
                Toggle::make('is_active')
                    ->label(__('filament-contact-form::contact.fields.active'))
                    ->default(true),
            ])
            ->columns(2);
    }

    private static function fieldsSection(): Section
    {
        return Section::make(__('filament-contact-form::contact.sections.fields'))
            ->description(__('filament-contact-form::contact.descriptions.fields'))
            ->schema([
                Select::make('phone_field')
                    ->label(__('filament-contact-form::contact.fields.phone'))
                    ->options(FieldVisibility::class)
                    ->enum(FieldVisibility::class)
                    ->default(FieldVisibility::Optional)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('company_field')
                    ->label(__('filament-contact-form::contact.fields.company'))
                    ->options(FieldVisibility::class)
                    ->enum(FieldVisibility::class)
                    ->default(FieldVisibility::Optional)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('subject_field')
                    ->label(__('filament-contact-form::contact.fields.subject'))
                    ->options(FieldVisibility::class)
                    ->enum(FieldVisibility::class)
                    ->default(FieldVisibility::Hidden)
                    ->selectablePlaceholder(false)
                    ->required(),
                Textarea::make('consent_label')
                    ->label(__('filament-contact-form::contact.fields.consent_label'))
                    ->helperText(__('filament-contact-form::contact.helpers.consent_label'))
                    ->maxLength(1000)
                    ->rows(2)
                    ->columnSpanFull(),
            ])
            ->columns(3);
    }

    private static function submissionSection(): Section
    {
        return Section::make(__('filament-contact-form::contact.sections.submission_settings'))
            ->schema([
                Textarea::make('thank_you_message')
                    ->label(__('filament-contact-form::contact.fields.thank_you_message'))
                    ->maxLength(65535),
                TextInput::make('redirect_url')
                    ->label(__('filament-contact-form::contact.fields.redirect_url'))
                    ->url()
                    ->maxLength(2048)
                    ->helperText(__('filament-contact-form::contact.helpers.redirect_url'))
                    ->rule('regex:#^https?://#i'),
            ])
            ->columns(2);
    }

    private static function crmSection(): Section
    {
        return Section::make(__('filament-contact-form::contact.sections.crm'))
            ->columnSpan(1)
            ->schema([
                Toggle::make('create_lead')
                    ->label(__('filament-contact-form::contact.fields.create_lead'))
                    ->helperText(__('filament-contact-form::contact.helpers.create_lead'))
                    ->default(true),
                TagsInput::make('notify_emails')
                    ->label(__('filament-contact-form::contact.fields.notify_emails'))
                    ->placeholder(__('filament-contact-form::contact.fields.add_email'))
                    ->helperText(__('filament-contact-form::contact.helpers.notify_emails'))
                    ->nestedRecursiveRules(['email']),
            ]);
    }

    private static function designSection(): Section
    {
        $selectOptions = static fn (array $values, string $prefix): array => collect($values)
            ->mapWithKeys(static fn (string $value): array => [$value => __("filament-contact-form::contact.design.{$prefix}.{$value}")])
            ->all();

        return Section::make(__('filament-contact-form::contact.sections.design'))
            ->schema([
                ColorPicker::make('design_tokens.primary_color')
                    ->label(__('filament-contact-form::contact.design.primary_color'))
                    ->default(DesignTokens::DEFAULT_PRIMARY_COLOR)
                    ->required(),
                Select::make('design_tokens.radius')
                    ->label(__('filament-contact-form::contact.design.radius_label'))
                    ->options($selectOptions(DesignTokens::RADII, 'radius'))
                    ->default(DesignTokens::RADIUS_MD)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('design_tokens.card_treatment')
                    ->label(__('filament-contact-form::contact.design.card_label'))
                    ->options($selectOptions(DesignTokens::CARD_TREATMENTS, 'card'))
                    ->default(DesignTokens::CARD_FLAT)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('design_tokens.input_background')
                    ->label(__('filament-contact-form::contact.design.input_bg_label'))
                    ->options($selectOptions(DesignTokens::INPUT_BACKGROUNDS, 'input_bg'))
                    ->default(DesignTokens::INPUT_BG_GRAY)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('design_tokens.submit_alignment')
                    ->label(__('filament-contact-form::contact.design.submit_label'))
                    ->options($selectOptions(DesignTokens::SUBMIT_ALIGNMENTS, 'submit'))
                    ->default(DesignTokens::SUBMIT_LEFT)
                    ->selectablePlaceholder(false)
                    ->required(),
                Select::make('design_tokens.max_width')
                    ->label(__('filament-contact-form::contact.design.width_label'))
                    ->options($selectOptions(DesignTokens::MAX_WIDTHS, 'width'))
                    ->default(DesignTokens::WIDTH_DEFAULT)
                    ->selectablePlaceholder(false)
                    ->required(),
            ])
            ->collapsed()
            ->columns(2);
    }

    private static function customCssSection(): Section
    {
        return Section::make(__('filament-contact-form::contact.sections.custom_css'))
            ->description(__('filament-contact-form::contact.descriptions.custom_css'))
            ->schema([
                CodeEditor::make('custom_css')
                    ->label(__('filament-contact-form::contact.fields.custom_css'))
                    ->language(Language::Css)
                    ->dehydrateStateUsing(static function (?string $state): ?string {
                        if ($state === null) {
                            return null;
                        }

                        $sanitized = CssSanitizer::sanitize(
                            $state,
                            (int) config('filament-contact-form.custom_css.max_length', CssSanitizer::DEFAULT_MAX_LENGTH),
                        );

                        return $sanitized === '' ? null : $sanitized;
                    })
                    ->columnSpanFull(),
            ])
            ->collapsed()
            ->visible((bool) config('filament-contact-form.custom_css.enabled', true));
    }
}
